"""Coverage report: what the training data teaches, per tool, cell, profile and source."""
from __future__ import annotations

import collections
from typing import Any

from .catalog import Tool
from .profiles import ORGANELLES, cell_active


def _tool_of(row: dict[str, Any]) -> str | None:
    ans = row["answers"]
    return ans[0]["name"] if ans and ans[0]["name"] != "done" else None


def analyse(rows: list[dict[str, Any]], catalog: list[Tool], profiles: dict[str, list[str]]) -> dict[str, Any]:
    train = [r for r in rows if r["meta"]["split"] == "train"]
    held = [r for r in rows if r["meta"]["split"] == "eval"]
    per_tool: dict[str, dict[str, int]] = {t.name: collections.Counter() for t in catalog}
    for split_name, subset in (("train", train), ("eval", held)):
        for r in subset:
            name = _tool_of(r)
            if name in per_tool:
                stage = r["meta"]["stage"]
                per_tool[name][f"{split_name}_{stage}"] += 1
                if r["meta"].get("history"):
                    per_tool[name][f"{split_name}_history"] += 1
    kinds = collections.Counter()
    for r in train:
        if r["meta"]["stage"] == "choose":
            kinds[r["meta"].get("kind", "tool")] += 1
    sources = collections.defaultdict(collections.Counter)
    for r in rows:
        sources[r["meta"].get("source", "?")][r["meta"]["split"]] += 1
    per_profile: dict[str, dict[str, Any]] = {}
    for name, cells in profiles.items():
        active = [t.name for t in catalog if cell_active(t.cell, cells)]
        covered = [n for n in active if per_tool[n]["train_choose"] > 0]
        prof_rows = [r for r in train if r["meta"].get("profile") == name and r["meta"]["stage"] == "choose"]
        per_profile[name] = {
            "cells": cells,
            "tools": len(active),
            "covered": len(covered),
            "choose_rows": len(prof_rows),
            "none_rows": sum(1 for r in prof_rows if r["meta"].get("kind") == "none"),
        }
    return {"per_tool": per_tool, "kinds": kinds, "sources": sources, "per_profile": per_profile, "train": len(train), "eval": len(held)}


def gaps(rows: list[dict[str, Any]], catalog: list[Tool], cells: list[str]) -> tuple[list[str], list[str]]:
    """For one profile: tools with no training choose-row, and tools with arguments but no arguments-row."""
    active = [t for t in catalog if cell_active(t.cell, cells)]
    choose: collections.Counter = collections.Counter()
    args: collections.Counter = collections.Counter()
    for r in rows:
        if r["meta"]["split"] != "train":
            continue
        name = _tool_of(r)
        if name:
            (choose if r["meta"]["stage"] == "choose" else args)[name] += 1
    no_choose = [t.name for t in active if choose[t.name] == 0]
    no_args = [t.name for t in active if t.parameters.get("properties") and choose[t.name] > 0 and args[t.name] == 0]
    return no_choose, no_args


def render(report: dict[str, Any], catalog: list[Tool], profiles: dict[str, list[str]], sizes: dict[str, tuple[int, int]] | None = None, excluded: list[str] | None = None) -> str:
    per_tool = report["per_tool"]
    cat_by_cell: dict[str, list[Tool]] = collections.defaultdict(list)
    for t in catalog:
        cat_by_cell[t.cell].append(t)
    out = ["# Training coverage", "",
           "Generated by `python -m hela_needle coverage`. Do not edit by hand; regenerate after changing seeds or the catalog.", "",
           f"- Agent catalog: **{len(catalog)} tools** that Needle is actually offered, across {len(cat_by_cell)} cells (see `data/catalog/agent-exclusions.json`)",
           f"- Rows: **{report['train']} train**, **{report['eval']} eval** (frozen)",
           f"- Train choose-rows by kind: " + ", ".join(f"{k} {v}" for k, v in sorted(report["kinds"].items())), "",
           "## By cell", "",
           "| Cell | Tools | With 1+ train row | With 3+ | Train choose | Train args | History | Eval | Profiles |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for cell in ORGANELLES + ["runtime"]:
        tools = cat_by_cell.get(cell, [])
        if not tools:
            continue
        ch = sum(per_tool[t.name]["train_choose"] for t in tools)
        ar = sum(per_tool[t.name]["train_arguments"] for t in tools)
        hi = sum(per_tool[t.name]["train_history"] for t in tools)
        ev = sum(per_tool[t.name]["eval_choose"] for t in tools)
        c1 = sum(1 for t in tools if per_tool[t.name]["train_choose"] >= 1)
        c3 = sum(1 for t in tools if per_tool[t.name]["train_choose"] >= 3)
        active_in = ", ".join(p for p, cells in profiles.items() if cell_active(cell, cells))
        out.append(f"| {cell} | {len(tools)} | {c1} | {c3} | {ch} | {ar} | {hi} | {ev} | {active_in} |")
    out += ["", "## By profile", "",
            "| Profile | Active cells | Tools | Covered (1+) | Train choose rows | None rows |", "|---|---|---:|---:|---:|---:|"]
    for name, info in report["per_profile"].items():
        out.append(f"| {name} | {', '.join(info['cells'])} | {info['tools']} | {info['covered']} | {info['choose_rows']} | {info['none_rows']} |")
    if sizes:
        out += ["", "## Per-profile models (dataset for a model dedicated to one profile)", "",
                "| Profile | Train rows | Eval rows |", "|---|---:|---:|"]
        for name, (tr, ev) in sizes.items():
            out.append(f"| {name} | {tr} | {ev} |")
    out += ["", "## By source file", "", "| Source | Train | Eval |", "|---|---:|---:|"]
    for src, c in sorted(report["sources"].items()):
        out.append(f"| {src} | {c['train']} | {c['eval']} |")
    out += ["", "## Gaps: tools with no train row", ""]
    for cell in ORGANELLES + ["runtime"]:
        missing = [t.name.replace("hela_", "", 1) for t in cat_by_cell.get(cell, []) if per_tool[t.name]["train_choose"] == 0]
        if missing:
            out.append(f"- **{cell}** ({len(missing)}): " + ", ".join(missing))
    if excluded:
        out += ["", f"## Not offered to Needle ({len(excluded)}): excluded by the agent catalog, so not trained", "",
                ", ".join(excluded)]
    thin = [(t.name.replace("hela_", "", 1), per_tool[t.name]["train_choose"]) for t in catalog if 0 < per_tool[t.name]["train_choose"] < 3]
    out += ["", f"## Thin: tools with fewer than 3 train rows ({len(thin)})", ""]
    out.append(", ".join(f"{n} ({c})" for n, c in thin) or "none")
    return "\n".join(out) + "\n"
